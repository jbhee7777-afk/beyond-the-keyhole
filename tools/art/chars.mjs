// 캐릭터 그림 (모카, 찍찍이, 소소)
// 원·타원을 겹쳐 만들지 않고, 손으로 찍은 점들을 부드럽게 이은 "한 줄 윤곽"으로 그린다.
// - 그늘 쪽 윤곽은 굵게, 빛 쪽은 가늘게 (선 굵기 변화)
// - 몸의 둥근 형태를 따라가는 그늘 + 빗금
// - 털 뭉치, 눈꺼풀, 눈썹, 주둥이 모양
import { wob, smooth, INK } from './ink.mjs';

const f1 = (n) => Math.round(n * 10) / 10;
let uid = 0;

// 닫힌 윤곽 (점을 그대로 지나가는 부드러운 곡선, 살짝 흔들림)
export const S = (pts, amp = 0.5) => wob(pts, { step: 999, amp });
// 열린 선
export const O = (pts, amp = 0.4) => wob(pts, { closed: false, step: 999, amp });
const strokeP = (d, sw, col = INK, op = 1) => `<path d="${d}" fill="none" stroke="${col}" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round"${op < 1 ? ` opacity="${op}"` : ''}/>`;

/**
 * 몸 부위 하나: 채색 → 안쪽 그늘(잘라내기) → 가는 윤곽 → 그늘 쪽 굵은 윤곽
 * heavy: [시작, 끝] 점 번호 구간을 굵게 덧그린다
 * shade: 부위 안에서만 보이는 그늘 모양(점 목록), hatch: 그늘에 빗금도 넣을지
 */
export function part(pts, fill, { heavy, sw = 2, hw = 3.6, shade, shadeCol = 'rgba(80,50,40,0.16)', hatch = true, extra = '', light } = {}) {
  // 꼭짓점이 4개 이하(사각형·삼각형)면 변을 잘게 나눠 곧은 변을 유지한다. 그냥 부드럽게 이으면 둥근 덩어리가 된다
  const d = pts.length <= 4 ? wob(pts, { step: 22, amp: 0.5 }) : S(pts);
  const id = 'c' + (uid++);
  let o = `<path d="${d}" fill="${fill}"/>`;
  if (shade || light || extra) {
    o += `<clipPath id="${id}"><path d="${d}"/></clipPath><g clip-path="url(#${id})">`;
    if (shade) {
      const sd = S(shade, 0.3);
      o += `<path d="${sd}" fill="${shadeCol}"/>`;
      if (hatch) o += `<path d="${sd}" fill="url(#hatch)" opacity="0.28"/>`;
    }
    if (light) o += `<path d="${S(light, 0.3)}" fill="#ffffff" opacity="0.35"/>`;
    o += extra + '</g>';
  }
  o += strokeP(d, sw);
  if (heavy) {
    const n = pts.length;
    const seg = [];
    for (let i = heavy[0]; i !== (heavy[1] + 1) % n; i = (i + 1) % n) seg.push(pts[i]);
    if (seg.length > 1) o += `<path d="${smooth(seg, false)}" fill="none" stroke="${INK}" stroke-width="${hw}" stroke-linecap="round"/>`;
  }
  return o;
}
// 털 뭉치: 기준점에서 바깥으로 짧은 삐침 몇 개
export function tufts(list, col = INK, sw = 1.4) {
  return list.map(([x, y, a, l]) => strokeP(O([[x, y], [x + Math.cos(a) * l * 0.6 + Math.sin(a) * 2, y + Math.sin(a) * l * 0.6 - Math.cos(a) * 2], [x + Math.cos(a) * l, y + Math.sin(a) * l]], 0.2), sw, col, 0.8)).join('');
}
const blush = (x, y, col = '#e98f95') => [0, 1, 2].map((k) => strokeP(O([[x - 9 + k * 6, y + 4], [x - 4 + k * 6, y - 4]], 0.2), 2.2, col, 0.75)).join('');
const dot = (x, y, r, c, op = 1) => `<circle cx="${f1(x)}" cy="${f1(y)}" r="${r}" fill="${c}"${op < 1 ? ` opacity="${op}"` : ''}/>`;

